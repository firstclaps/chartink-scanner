# YOUR MACD SCANNER (✅ WORKS)
SCAN_CLAUSE = "( {33489} ( ( {33489} ( daily macd histogram( 26,24,25 ) > 0 and 1 day ago macd histogram( 26,24,25 ) < 0 ) ) or( {33489} ( daily macd histogram( 26,24,25 ) < 0 and 1 day ago macd histogram( 26,24,25 ) > 0 ) ) ) )"

def is_market_day():
    today = datetime.now().weekday()
    return 0 <= today <= 4

def fetch_chartink_macd_screener():
    session = requests.Session()
    resp = session.get("https://chartink.com/screener")
    resp.raise_for_status()
    soup = BeautifulSoup(resp.text, "lxml")
    csrf_token = soup.select_one('meta[name="csrf-token"]')['content']

    payload = {"scan_clause": SCAN_CLAUSE}
    session.headers["X-CSRF-TOKEN"] = csrf_token
    session.headers["Content-Type"] = "application/x-www-form-urlencoded"

    r = session.post("https://chartink.com/screener/process", data=payload)
    r.raise_for_status()

    data = r.json()
    if not data.get("data") or len(data["data"]) == 0:
        return pd.DataFrame()

    num_cols = len(data["data"][0])
    df = pd.DataFrame(data["data"])
    headers = ["S.No", "SYMBOL", "NAME", "","% from 52WH", "% from 52WL", "Price"][:num_cols]
    df.columns = headers
    return df

